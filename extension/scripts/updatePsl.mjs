// Writes publicSuffixList.js from the Public Suffix List (its repository,
// github.com/publicsuffix/list): every rule, ICANN
// and private sections (github.io, uk.com, trycloudflare.com…), Unicode
// rules converted to punycode (hosts in URLs are ASCII). Run with `make psl`
// every few months (CLAUDE.md, "Periodic maintenance").
// `--check`: writes nothing; says whether the bundled list differs from the
// current one — exit 3 when it does (the monthly psl.yml workflow opens an
// issue), any other failure (download, parse) is a plain error.
import { readFileSync, writeFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// The list's own repository: publicsuffix.org's copy sits behind a CDN that
// caches it for a day (max-age 86400), so two runs could see two versions
// and the monthly check would cry wolf.
const SOURCE = 'https://raw.githubusercontent.com/publicsuffix/list/main/public_suffix_list.dat';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'publicSuffixList.js');

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: ${res.status}`);
const text = await res.text();

const rules = new Set();
for (const raw of text.split('\n')) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith('//')) continue;
  // "!" (exception) and "*." (wildcard) are kept; the rest of the rule in punycode.
  const prefix = line.startsWith('!') ? '!' : '';
  const body = line.slice(prefix.length);
  const wild = body.startsWith('*.') ? '*.' : '';
  const name = body.slice(wild.length);
  const ascii = domainToASCII(name);
  if (!ascii) throw new Error(`unreadable rule: ${line}`);
  rules.add(`${prefix}${wild}${ascii.toLowerCase()}`);
}
if (rules.size < 5000 || !rules.has('com') || !rules.has('github.io')) throw new Error(`suspicious list: ${rules.size} rules`);

const list = [...rules].sort();
if (process.argv.includes('--check')) {
  const bundled = readFileSync(out, 'utf8');
  const date = /PUBLIC_SUFFIX_UPDATED = '([\d-]+)'/.exec(bundled)?.[1] || 'unknown';
  const have = new Set((/PUBLIC_SUFFIX_RULES = '([^']*)'/.exec(bundled)?.[1] || '').split(',').filter(Boolean));
  const added = list.filter(r => !have.has(r));
  const removed = [...have].filter(r => !rules.has(r));
  if (!added.length && !removed.length) { console.log(`publicSuffixList.js (${date}) is up to date.`); process.exit(0); }
  console.log(`publicSuffixList.js (${date}) is behind: ${added.length} rules added, ${removed.length} removed upstream.`);
  if (added.length) console.log(`Added: ${added.slice(0, 40).join(', ')}${added.length > 40 ? ', …' : ''}`);
  if (removed.length) console.log(`Removed: ${removed.slice(0, 40).join(', ')}${removed.length > 40 ? ', …' : ''}`);
  process.exit(3);
}
const updated = new Date().toISOString().slice(0, 10);
writeFileSync(out, `// Generated by \`make psl\` (scripts/updatePsl.mjs) from ${SOURCE}. Do not edit.
// ${list.length} rules (ICANN and private). Refresh every 3 months: CLAUDE.md, "Periodic maintenance".
'use strict';
const PUBLIC_SUFFIX_UPDATED = '${updated}';
const PUBLIC_SUFFIX_RULES = '${list.join(',')}';
`);
console.log(`publicSuffixList.js: ${list.length} rules, ${updated}`);
